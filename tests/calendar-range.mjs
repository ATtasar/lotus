import assert from 'node:assert/strict';
import { calendarRangeWeeks } from '../desktop/workbench-model.js';
import { initialData, mergeBackup, validateBackup } from '../desktop/model.js';

const order = (id, start, due) => ({ id, start, due });
const data = [order('long', '2026-09-28', '2026-11-02'), order('b', '2026-10-07', '2026-10-09'), order('c', '2026-10-09', '2026-10-12'), order('d', '2026-10-10', '2026-10-12'), order('before', '2026-09-20', '2026-10-04'), order('after', '2026-11-09', '2026-11-12')];
const weeks = calendarRangeWeeks(data, '2026-10-05', 35);
assert.equal(weeks.length, 5);
assert.ok(weeks.every((week) => week.find((s) => s.order.id === 'long').lane === 0));
const first = weeks[0].find((s) => s.order.id === 'long');
assert.deepEqual([first.column, first.span, first.continuesBefore, first.continuesAfter], [1, 7, true, true]);
const last = weeks[4].find((s) => s.order.id === 'long');
assert.deepEqual([last.column, last.span, last.continuesBefore, last.continuesAfter], [1, 1, true, false]);
const lookup = (id) => weeks[0].find((s) => s.order.id === id);
assert.notEqual(lookup('b').lane, lookup('c').lane, 'shared end/start day must use different lanes');
assert.equal(lookup('b').lane, lookup('d').lane, 'non-overlapping intervals can reuse a lane');
assert.ok(weeks.flat().every((s) => !['before', 'after'].includes(s.order.id)));
const single = calendarRangeWeeks([order('single', '2026-10-11', '2026-10-11')], '2026-10-05')[0][0];
assert.deepEqual([single.column, single.span, single.continuesBefore, single.continuesAfter], [7, 1, false, false]);
const leap = calendarRangeWeeks([order('leap', '2028-02-28', '2028-03-01')], '2028-02-28')[0][0];
assert.equal(leap.span, 3);
const dst = calendarRangeWeeks([order('dst', '2026-03-23', '2026-03-29')], '2026-03-23')[0][0];
assert.equal(dst.span, 7, 'civil dates must not lose a day across daylight-saving transitions');
assert.deepEqual(calendarRangeWeeks([], '2026-10-05', 14), [[], []]);
for (const count of [0, 5, 8, 90]) assert.throws(() => calendarRangeWeeks([], '2026-10-05', count));
const legacy = initialData(); delete legacy.scheduleView;
assert.equal(validateBackup(legacy).scheduleView, 'deadline');
const current = initialData(); current.scheduleView = 'range';
assert.equal(mergeBackup(current, initialData()).scheduleView, 'range', 'merging records must preserve PC display preferences');
assert.throws(() => validateBackup({ ...initialData(), scheduleView: 'invalid' }), /样式/);
console.log('PASS: continuous date bars, inclusive endpoints, overlap lanes, cross-week/month clipping, leap/DST dates and compatible saved display choice.');
