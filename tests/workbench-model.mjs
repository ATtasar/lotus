import assert from 'node:assert/strict';
import { monthIncome, sortedClients, updateOrderDates, sortActive, sortEnded, paginate } from '../desktop/workbench-model.js';
import { initialData, validateBackup, mergeBackup } from '../desktop/model.js';
const make = (id, status, due, deposit = 100) => ({ id, status, due, deposit, balance: 200, extras: [{ name: '服务', amount: 10 }] });
const orders = [make('active', '草稿', '2026-10-22'), make('done', '完成', '2026-10-21'), make('cancel', '退单', '2026-10-23'), make('next', '完成', '2026-11-01')];
assert.deepEqual(monthIncome(orders, '2026-10'), { actual: 310, predicted: 930 });
const previous = structuredClone(orders[0]);
orders[0].status = '完成';
updateOrderDates(orders[0], previous, '2026-10-20T10:00:00.000Z');
assert.equal(orders[0].endedAt, '2026-10-20T10:00:00.000Z');
const saved = structuredClone(orders[0]);
updateOrderDates(orders[0], saved, '2026-10-21T10:00:00.000Z');
assert.equal(orders[0].endedAt, saved.endedAt, 'editing a completed order must not change completion ordering');
orders[0].status = '草稿'; updateOrderDates(orders[0], saved);
assert.equal(orders[0].endedAt, undefined);
const clients = [{ id: 'old' }, { id: 'recent' }, { id: 'new', createdAt: '2026-10-18T00:00:00Z' }, { id: 'import', importedAt: '2026-10-20T00:00:00Z' }];
assert.deepEqual(sortedClients(clients, [{ client: 'old', start: '2026-09-01' }, { client: 'recent', start: '2026-10-19' }]).map((item) => item.id), ['import', 'new', 'recent', 'old']);
const many = Array.from({ length: 103 }, (_, i) => make(String(i), '未开始', `2026-10-${String(1 + i % 28).padStart(2, '0')}`));
assert.equal(paginate(sortActive(many), 2, 20).items.length, 20);
assert.equal(paginate(many, 3, 50).items.length, 3);
assert.equal(paginate([], 90, 20).page, 1);
assert.equal(sortEnded([{ id: 'a', due: '2026-10-29' }, { id: 'b', due: '2026-10-20', endedAt: '2026-10-30T10:00:00Z' }])[0].id, 'b');
const data = initialData();
data.platforms.push({ id: 'p', name: '平台', color: '#333333', fee: 0 });
data.templates.push({ id: 't', title: '模板', category: '头像', platform: 'p', deposit: 100, balance: 200, fee: 0, requirements: '', stages: ['未开始', '成图', '完成'], images: [], extras: [] });
data.replyFolders.push({ id: 'f', name: '订单回复', parent: '' }, { id: 'child', name: '子分组', parent: 'f' });
data.replyTemplates.push({ id: 'r', title: '确认', body: '请确认要求', parent: 'child', templateIds: ['t'] });
data.priceEntries.push({ id: 'e', name: '头像', price: 300, description: '', bg: '#ffffff', color: '#222222', fit: 'cover', image: '' });
data.priceLists.push({ id: 'l', name: '价目表', bg: '#eeeeee', backgroundImage: '', width: 1200, columns: 2, cardHeight: 540, gap: 24, padding: 48, items: [structuredClone(data.priceEntries[0])] });
const merged = mergeBackup(data, data);
assert.equal(merged.priceEntries.length, 2);
assert.equal(merged.priceLists.length, 2);
assert.equal(merged.replyTemplates.length, 2);
assert.equal(merged.replyTemplates[1].templateIds[0], merged.templates[1].id);
assert.equal(merged.replyTemplates[1].parent, merged.replyFolders[3].id);
const cycle = structuredClone(data); cycle.replyFolders[0].parent = 'child';
assert.throws(() => validateBackup(cycle), /循环/);
const missing = structuredClone(data); missing.replyTemplates[0].templateIds = ['missing'];
assert.throws(() => validateBackup(missing), /关联/);
console.log('PASS: income, client priority, completion dates, 20/50 pagination, additive backup merge and association validation');
